// AI_NOTE: scopeに対応する設計mdのリポジトリルートからの相対パス。呼び出し側(コマンド/webviewハンドラ)が
// 「既存の設計mdがあるか」を判定して更新モードに切り替えるために使う(パス規則をここ1箇所に集約)。
export function designRelPathForScope(scope: DesignScope): string {
    if (scope.kind === "repo") return ".ai-code-guide/design/_repo.md";
    if (scope.kind === "directory") return `.ai-code-guide/design/${scope.relPath}/_dir.md`;
    return `.ai-code-guide/design/${scope.relPath}.md`;
}

// AI_NOTE: 更新モード。既存mdを出発点に、@confirmed(開発者確認済み=一番高価な資産)は原則維持し、
// @inferred/切れたanchor/欠けたセクションだけ下書きし直させる。新規作成プロンプトを再利用すると
// @confirmedが全部捨てられて@inferred下書きに戻ってしまう問題への対処。
function buildUpdateSection(existingMd: string): string {
    return `

## 既存の設計ファイル（今回は更新）

今回は新規作成ではなく、下記の既存設計ファイルの更新です。手順1の下書きは白紙からではなく、この既存内容を出発点にしてください:

- \`@confirmed\` の記述は開発者が確認済みの資産なので、原則そのまま維持してください。現在のコードと明らかに矛盾する場合だけ、開発者に確認して直してください（直した記述は \`@confirmed\` の日付を更新）。
- \`@inferred\` の記述・現在のコード中に見つからなくなった anchor・フォーマット仕様で必須なのに欠けているセクションは、下書きし直して開発者の確認にかけてください。

\`\`\`markdown
${existingMd}
\`\`\``;
}

// AI_NOTE: 依頼プロンプトの本体。貼られた先のエージェントがこのリポの文脈なしで動けるよう、
// 役割/ヒアリング手順/置き場/フォーマット仕様/対象範囲/完了条件を全て自己完結で埋め込む。
// existingMd を渡すと更新モード(既存mdを埋め込み@confirmed維持ルールを追加)になる。
export function buildDesignPrompt(scope: DesignScope, existingMd?: string): string {
    const { rangeText, outputPathExample } = describeScope(scope);

    return `あなたにこのリポジトリの「設計ファイル」を作ってほしいです。

## 設計ファイルとは

コードから逆生成した設計は、定義上コードと必ず一致してしまうため「意図と実装のズレ」を検出する用途には使えません。設計ファイルは、コードとは別に人（このリポの開発者）が確認した「意図の独立ソース」です。だからこそ本体はAIの自動生成そのものではなく、開発者による確認です。ただし白紙の質問は答えにくいので、まずあなたが下書きし、開発者には正誤判定と修正だけしてもらいます。

## 手順（下書き→開発者の確認）

0. 対象より上の層の設計ファイルが \`.ai-code-guide/design/\` にあれば先に読んでください（層は リポ全体 \`_repo.md\` → ディレクトリ \`_dir.md\` → ファイル → 関数 の順。例: ファイルが対象なら \`_repo.md\` と親ディレクトリの \`_dir.md\`）。そこにある \`@confirmed\` の記述（特にリポの「誰のどんな問題を解くか」「主要ユースケース」）を起点に「この対象はどんな目的・設計であるべきか」を先に導き、その仮説をコードと突き合わせて下書きします。コードの要約を目的欄に書くのではなく、上の層から導いた目的にコードが合っているかを見る、という向きです。上の層に \`@confirmed\` の記述が無い場合はコードからの推測に頼ることになるので、その旨を開発者に伝え、可能なら先に上の層の確認を勧めてください。
1. あなたがコード・README・コミット履歴を読み、対象範囲の全セクションの下書きを書いてください。この時点の記述にはすべて \`<!-- @inferred -->\` タグを付けます（コードから推測しただけで、開発者が確認した事実ではないことを示すため）。
2. 下書きを開発者に見せ、項目ごとに「合っている / 違う（正しい内容を聞く）/ 分からない」を確認してください。目的・要件・方針は特に、検討したが採用しなかった代替案があれば聞き足してください。${scope.kind === "repo" ? "対象がリポジトリ全体なので、「誰のどんな問題を解くか」「主要なユースケース（2〜3個）」の2セクションはコードにほぼ写らない情報で下書きが外れやすいです。この2つは必ず確認にかけ、開発者の回答を反映してください。" : ""}
3. 開発者が「合っている」と認めた・修正して確定した項目は、タグを \`<!-- @confirmed [YYYY-MM-DD] -->\`（日付が分からなければ日付なしの \`<!-- @confirmed -->\` でも可）に書き換えてください。開発者にも分からなかった項目は \`@inferred\` のまま残します。
4. 出所タグ（@confirmed/@inferred）は、目的・要件/制約の箇条書き・方針の各セクション単位で付けます。タグが無い記述は「未確認」として扱われます。
5. 最後に、下書きの過程で気づいた設計への疑問（上の層の目的に対して責務が混ざっている・ユースケースに無い複雑さがある・境界が曖昧、など）があれば、チャット上で疑問リストとして開発者に投げてください。妥当な設計は複数ありうるので「〜は意図的ですか？」の質問の形にし、断定しないこと。このリストは設計ファイル本文には書きません（設計ファイルは合意した意図の記録で、未解決の疑問とは寿命が違うため）。無理に絞り出さず、無ければ「疑問なし」でかまいません。

## 置き場のパス規則

設計ファイルは \`.ai-code-guide/design/\` の下に、ソースコードと同じフォルダ構造を複製して置きます（ソース側のフォルダには混ぜません）。

- リポ全体: \`.ai-code-guide/design/_repo.md\`
- ディレクトリ単位: \`.ai-code-guide/design/<dir>/_dir.md\`
- ファイル単位: \`.ai-code-guide/design/<relpath>.md\`（例: \`src/search.py\` → \`.ai-code-guide/design/src/search.py.md\`。ドットが2つ並びますが、ソース側に \`search.md\` があった場合との衝突を避けるためわざとこの形にしています）

関数・クラス単位は独立ファイルにしません。ファイル単位のmdの中に、ファイルの説明→各関数/クラスの説明を、ソースコードの実装順で並べてください。

## フォーマット仕様

固定セクションのMarkdownです。以下の記入例の見出し・記法（\`##\` \`###\` の階層、\`→ anchor: "..."\` の書式、コメントタグの位置）を一字一句そのまま守ってください。崩すと自動検証（パーサ）が読み取れません。

\`\`\`markdown
${FORMAT_EXAMPLE}
\`\`\`

- 先頭のfrontmatter（\`source_file:\`）は必須です。値はこのファイルのリポジトリルートからの相対パスにしてください。
- \`## 関数: <名前>\` / \`## クラス: <名前>\` はファイル内に必要なだけ繰り返せます。
- \`### 構成\` のアンカー（\`anchor: "..."\`）は、対応するコード断片をテキスト完全一致で書いてください（行番号は使いません。編集で行がずれても対応が壊れないようにするためです）。長すぎず、かつファイル内で他と紛れない断片を選んでください。
- ディレクトリ単位（\`_dir.md\`）・リポ単位（\`_repo.md\`）には frontmatter や関数/クラスセクションは不要です。\`_dir.md\` は「## 目的」を中心に、責務・内部の分担を自由記述してください。\`_repo.md\` は先頭の「## 誰のどんな問題を解くか」「## 主要ユースケース」の2セクションが必須で、その後の全体設計・ディレクトリ分担は自由記述です。

## 対象範囲

${rangeText}

出力先の例: \`${outputPathExample}\`
${existingMd ? buildUpdateSection(existingMd) : ""}
## 完了条件

ファイルを書き終えたら、\`### 構成\`に書いた各anchorの文字列が対応するソースコード中に完全一致で実在することを、自分で検索して確認してください（見つからないと自動検証で警告が出ます）。`;
}

// AI_NOTE: 設計ファイル機能フェーズ1ステップ2。ai-code-guide自身は設計mdを生成せず、
// Claude Code/codex等の外部エージェントに書かせる。ここではその「依頼プロンプト」を組み立てるだけ
// （vscode非依存・拡張側はコピー&貼り付け導線のみ持つ）。フォーマット仕様は designParser.ts の
// 文法サマリと完全一致させること（乖離するとparseDesignFile側でerror issueになる）。

export type DesignScope =
    | { kind: "repo" }
    | { kind: "directory"; relPath: string }
    | { kind: "file"; relPath: string };

// AI_NOTE: scope種別ごとに「対象範囲」節の文言と、置き場パス規則に沿った出力先パス例を作る。
// パス例はユーザーがそのまま流用できるよう scope の relPath を実際に埋め込む。
// AI_NOTE: repoスコープはContext層（誰の問題・主要ユースケース）の2セクションを必須にする。
// この2つはコードから推測しても当たりにくいため、手順側でも必ず開発者の確認にかけるよう指示する
// （パーサ検証は無し＝自由記述のまま）。
// AI_NOTE: 手順は「開発者に白紙で聞く」でなく「AIが@inferredで全下書き→開発者が項目ごとに正誤判定
// →OK項目だけ@confirmedへ書き換え」。白紙の質問より下書きの正誤判定の方が人の負荷が低く、
// 確認の質（最終的に人を通す）は変わらないため。
// AI_NOTE: 手順0=生成の向きの規定。下の層の目的をコードの要約で埋めると「コードを正当化するだけの設計」
// になるため、上の層の@confirmed(コードと独立な意図)から導出→コードと突き合わせの順にする。
// 起点にできるのは@confirmedのみ(未確認層からの導出はコードに引っ張られた推測の連鎖に戻る)。
// 手順5=設計への疑問はチャットで質問形・設計md本文に混ぜない(合意記録と未解決疑問は寿命が違う)。
function describeScope(scope: DesignScope): { rangeText: string; outputPathExample: string } {
    if (scope.kind === "repo") {
        return {
            rangeText: "リポジトリ全体。まず `.ai-code-guide/design/_repo.md` を書き、続けて主要なディレクトリごとに `<dir>/_dir.md` を書いてください。`_repo.md` の先頭には必ず「## 誰のどんな問題を解くか」「## 主要ユースケース」（2〜3個の箇条書き）の2セクションを置き、その後に全体設計・ディレクトリ分担を続けてください。",
            outputPathExample: ".ai-code-guide/design/_repo.md 、 .ai-code-guide/design/<dir>/_dir.md",
        };
    }
    if (scope.kind === "directory") {
        return {
            rangeText: `ディレクトリ \`${scope.relPath}\`。このディレクトリの責務・内部の分担を \`_dir.md\` に書いてください。`,
            outputPathExample: `.ai-code-guide/design/${scope.relPath}/_dir.md`,
        };
    }
    return {
        rangeText: `ファイル \`${scope.relPath}\`。このファイルの目的と、中の関数・クラスそれぞれの目的/要件・制約/方針/構成を書いてください。`,
        outputPathExample: `.ai-code-guide/design/${scope.relPath}.md`,
    };
}

